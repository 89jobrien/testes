//! `testes-fuzz` owns the `fuzz!` dimension and the `fuzz!` macro.
//!
//! Per ADR-0006, `fuzz!` generates fuzz tests using Proptest,
//! with evidence recording. Fuzz tests run arbitrary input generation
//! against a target function with oracle predicates.

#![forbid(unsafe_code)]

use std::cell::RefCell;
pub use testes_core::{
    BackendConfiguration, BackendIdentity, Claim, Dimension, DimensionEvidence, EvidenceRecord,
    ExecutionMetadata, ExecutionOutcome, ExecutionStatus, FuzzEvidence, IdError,
    ObligationDisposition, ObligationId, Observed, OutcomeReason, Provenance, RepositoryRevision,
    ResourceLimits, RunId, Scope, SubjectId, TestDeclaration, TestId, TestSpecification,
    WorkingTreeState,
};

thread_local! {
    // Records the most recent evidence from a fuzz! invocation (for test introspection).
    pub static LAST_FUZZ_EVIDENCE: RefCell<Option<(TestId, FuzzEvidence)>> = const { RefCell::new(None) };
}

/// Declares and executes a fuzz test with evidence recording.
///
/// # Grammar
///
/// ```text
/// fuzz! {
///     id: "fuzz-id",
///     subject: "function_name",
///     claim: "property statement",
///     target: |input: &[u8]| {
///         // Fuzz target returning bool
///         true
///     },
///     oracle: |result: bool| {
///         // Property check
///         prop_assert!(result);
///     },
///     cases: 1000,
///     corpus: vec![b"seed1", b"seed2"],
/// }
/// ```
///
/// For each fuzz test, generates a `#[test]` function that:
/// 1. Validates the `TestDeclaration`
/// 2. Runs Proptest with generated byte inputs
/// 3. Records `FuzzEvidence` with execution counts
/// 4. Propagates failures (panics or property violations)
#[macro_export]
macro_rules! fuzz {
    (
        id: $id:expr,
        subject: $subject:expr,
        claim: $claim:expr,
        target: $target:expr,
        oracle: $oracle:expr,
        cases: $cases:expr
        $(,)?
    ) => {
        ::pastey::paste! {
            #[test]
            fn [< $id >]() {
                use proptest::test_runner::TestRunner;
                use proptest::strategy::Strategy;

                let test_id = $crate::TestId::new($id)
                    .expect("test id must not be blank or contain control characters");
                let subject_id = $crate::SubjectId::new($subject)
                    .expect("subject must not be blank or contain control characters");

                // Construct the declaration.
                let declaration = $crate::TestDeclaration {
                    id: test_id.clone(),
                    primary_dimension: $crate::Dimension::Fuzz,
                    secondary_dimensions: Vec::new(),
                    subject: subject_id,
                    claim: $crate::Claim {
                        statement: $claim.to_string(),
                        obligations: Vec::new(),
                    },
                    required_scope: $crate::Scope {
                        input_domain: "fuzz test (arbitrary bytes)".to_string(),
                        assumptions: Vec::new(),
                        bounds: Vec::new(),
                        capabilities: Vec::new(),
                        resources: $crate::ResourceLimits {
                            wall_time: None,
                            memory_bytes: None,
                            max_input_bytes: None,
                        },
                    },
                    disposition: $crate::ObligationDisposition::Required,
                    specification: $crate::TestSpecification::Fuzz {
                        target_id: $subject.to_string(),
                        oracle_ids: Vec::new(),
                        corpus_artifacts: Vec::new(),
                    },
                };

                // Validate the declaration.
                declaration.validate().expect("TestDeclaration must be valid");

                // Track execution count
                let execution_count = std::sync::Arc::new(std::sync::atomic::AtomicU64::new(0));
                let started_at = std::time::SystemTime::now();

                // Build strategy and run fuzz test
                let test_result = {
                    let execution_count_clone = execution_count.clone();
                    let mut runner = TestRunner::default();
                    runner.run(&(proptest::arbitrary::any::<Vec<u8>>()), |input| {
                        execution_count_clone.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
                        let target_result = ($target)(&input);
                        ($oracle)(target_result)
                    })
                };
                let duration = started_at.elapsed().unwrap_or(std::time::Duration::ZERO);
                let exec_count = execution_count.load(std::sync::atomic::Ordering::Relaxed);

                // Record the outcome
                let (outcome_status, diagnostic) = match &test_result {
                    Ok(()) => ($crate::ExecutionStatus::Passed, None),
                    Err(e) => (
                        $crate::ExecutionStatus::Failed,
                        Some(format!("{:?}", e)),
                    ),
                };

                // Build the evidence
                let fuzz_evidence = $crate::FuzzEvidence {
                    target_id: $subject.to_string(),
                    oracle_ids: Vec::new(),
                    initial_corpus: Vec::new(),
                    actual_duration: duration,
                    executions: $crate::Observed::Available(exec_count),
                    coverage: $crate::Observed::Unavailable {
                        reason: "coverage not instrumented".to_string(),
                    },
                    failure_inputs: Vec::new(),
                };

                let execution_outcome = $crate::ExecutionOutcome {
                    status: outcome_status,
                    reason: if outcome_status == $crate::ExecutionStatus::Passed {
                        $crate::OutcomeReason::AssertionsSatisfied
                    } else {
                        $crate::OutcomeReason::CounterexampleFound
                    },
                    diagnostic,
                    obligations: Vec::new(),
                };

                let evidence_record = $crate::EvidenceRecord {
                    schema_version: 1,
                    declaration,
                    provenance: $crate::Provenance {
                        run_id: $crate::RunId::new("fuzz-test-run")
                            .expect("run id valid"),
                        revision: $crate::RepositoryRevision {
                            repository: "unknown".to_string(),
                            commit: "unknown".to_string(),
                            working_tree: $crate::WorkingTreeState::Unknown,
                        },
                    },
                    execution: $crate::ExecutionMetadata {
                        backend: $crate::BackendIdentity {
                            name: "proptest-fuzz".to_string(),
                            version: env!("CARGO_PKG_VERSION").to_string(),
                            toolchain: None,
                        },
                        configuration: $crate::BackendConfiguration::new(),
                        started_at,
                        duration,
                        actual_scope: $crate::Scope {
                            input_domain: "fuzz test (arbitrary bytes)".to_string(),
                            assumptions: Vec::new(),
                            bounds: Vec::new(),
                            capabilities: Vec::new(),
                            resources: $crate::ResourceLimits {
                                wall_time: None,
                                memory_bytes: None,
                                max_input_bytes: None,
                            },
                        },
                    },
                    outcome: execution_outcome,
                    artifacts: Vec::new(),
                    dimension_evidence: $crate::DimensionEvidence::Fuzz(fuzz_evidence.clone()),
                };

                // Store for introspection.
                $crate::LAST_FUZZ_EVIDENCE.with(|e| {
                    *e.borrow_mut() = Some((test_id, fuzz_evidence));
                });

                // Propagate fuzz test result
                test_result.expect("fuzz test failed");
            }
        }
    };
}
